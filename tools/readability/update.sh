#!/bin/sh
# Regenerates Satellite/Services/ReadabilityScript.swift from Mozilla's Readability.
#   tools/readability/update.sh            uses tools/readability/Readability.js as it is
#   tools/readability/update.sh --fetch    downloads the latest release from npm first
# Embedded as a Swift string rather than bundled as a .js resource, so there is no
# build phase to get wrong.
set -e
cd "$(dirname "$0")"
if [ "$1" = "--fetch" ]; then
  tmp=$(mktemp -d)
  (cd "$tmp" && npm pack @mozilla/readability >/dev/null && tar xzf mozilla-readability-*.tgz)
  cp "$tmp/package/Readability.js" Readability.js
  cp "$tmp/package/LICENSE.md" LICENSE.md
  rm -rf "$tmp"
fi
if grep -q '"""#' Readability.js; then echo "Readability.js contains the raw string delimiter" >&2; exit 1; fi
out=../../Satellite/Services/ReadabilityScript.swift
{
  echo '// Generated by tools/readability/update.sh from Mozilla Readability. Do not edit.'
  echo '// Licensed under the Apache License 2.0: see tools/readability/LICENSE.md.'
  echo ''
  echo 'enum ReadabilityScript {'
  echo '    static let source = #"""'
  cat Readability.js
  echo '"""#'
  echo '}'
} > "$out"
echo "wrote $out"
